static int sensor_power(int on)
{
	switch(on){
	case PWR_ON:
		printf("amp gc4663 PWR_ON\n");
		udelay(1000);
		vin_gpio_set_status(SENSOR_PWDN_PIN, 1);
		vin_gpio_set_status(SENSOR_RESET_PIN, 1);
		vin_gpio_write(SENSOR_RESET_PIN, CSI_GPIO_LOW);
		vin_gpio_write(SENSOR_PWDN_PIN, CSI_GPIO_LOW);
		vin_set_mclk(0, 1);
		udelay(1000);
		vin_gpio_write(SENSOR_PWDN_PIN, CSI_GPIO_HIGH);
		vin_gpio_write(SENSOR_RESET_PIN, CSI_GPIO_HIGH);
		udelay(1000);
		break;
	default:
		break;
	}

	return 0;
}

static int sensor_reg_init(void)
{
	int ret;

	ret = sensor_write_array(SENSOR_TWI_IOBASE, SENSOR_TWI_ADDR, SENSOR_REG_ADDR_WIDTH, sensor_2560_1440_15fps_regs, ARRAY_SIZE(sensor_2560_1440_15fps_regs));
	if(ret < 0) {
		printf("sensor twi write error!\n");
		return -1;
	}

	return 0;
}

static void twi_pin_init(void)
{
	sunxi_gpio_set_cfgpin(SENSOR_TWI_SCL_PIN, SENSOR_TWI_SCL_PIN_FUNC);
	sunxi_gpio_set_cfgpin(SENSOR_TWI_SDA_PIN, SENSOR_TWI_SDA_PIN_FUNC);
}

int sensor_init(void)
{
	int ret;

	printf("amp gc4663 sensor_init\n");

	twi_init(SENSOR_TWI_IOBASE, SENSOR_TWI_SPEED);
	twi_pin_init();

	ret = sensor_power(1);
	if(ret < 0)
		return -1;

	ret = sensor_reg_init();
	if(ret < 0)
		return -1;

	printf("sensor init ok\n");
	return 0;
}



